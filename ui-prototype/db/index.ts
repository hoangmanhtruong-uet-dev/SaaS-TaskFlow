import { drizzle } from "drizzle-orm/postgres-js";
import postgres from "postgres";
import { databaseEnv } from "@/app/lib/env";
import * as schema from "./schema";

let client: ReturnType<typeof postgres> | undefined;
let database: unknown;

type QueryLike = PromiseLike<unknown[]> & {
  limit?: (count: number) => QueryLike;
  toSQL?: () => { sql: string; params: unknown[] };
};

function wrapQuery<T extends object>(value: T): T {
  return new Proxy(value, {
    get(target, property, receiver) {
      if (property === "get") {
        return async () => {
          const query = target as QueryLike;
          const rows = await (query.limit ? query.limit(1) : query);
          return rows[0];
        };
      }
      if (property === "all" || property === "run") {
        return async () => await (target as unknown as PromiseLike<unknown>);
      }

      const member = Reflect.get(target, property, receiver) as unknown;
      if (typeof member !== "function") return member;
      return (...args: unknown[]) => {
        const result = Reflect.apply(member, target, args) as unknown;
        return result && typeof result === "object" ? wrapQuery(result) : result;
      };
    },
  });
}

function wrapDatabase<T extends object>(raw: T, allowNativeTransaction = true): T {
  return new Proxy(raw, {
    get(target, property, receiver) {
      if (property === "transaction" && allowNativeTransaction) {
        return async (callback: (transaction: unknown) => Promise<unknown>) => {
          const transactionMethod = Reflect.get(target, property, receiver) as (handler: (tx: object) => Promise<unknown>) => Promise<unknown>;
          return transactionMethod.call(target, async (tx: object) => callback(wrapDatabase(tx, false)));
        };
      }
      const member = Reflect.get(target, property, receiver) as unknown;
      if (typeof member !== "function") return member;
      return (...args: unknown[]) => {
        const result = Reflect.apply(member, target, args) as unknown;
        return result && typeof result === "object" ? wrapQuery(result) : result;
      };
    },
  });
}

// Compatibility methods keep existing repository contracts stable during the
// SQLite-to-Postgres cutover. All SQL is still generated by the Postgres dialect.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export function getDb(): any {
  if (database) return database;
  if (!client) {
    const env = databaseEnv();
    client = postgres({
      host: env.SUPABASE_DB_HOST,
      port: env.SUPABASE_DB_PORT,
      user: env.SUPABASE_DB_USER,
      password: env.SUPABASE_DB_PASSWORD,
      database: env.SUPABASE_DB_NAME,
      max: 5,
      prepare: false,
      idle_timeout: 20,
      connect_timeout: 10,
      ssl: "require",
    });
  }

  const raw = drizzle(client, { schema });
  database = new Proxy(raw, {
    get(target, property, receiver) {
      if (property === "batch") {
        return async (queries: QueryLike[]) => client!.begin(async (transaction) => {
          const results: unknown[] = [];
          for (const query of queries) {
            if (!query.toSQL) throw new Error("Unsupported Postgres batch query");
            const built = query.toSQL();
            results.push(await transaction.unsafe(built.sql, built.params as never[]));
          }
          return results;
        });
      }
      if (property === "transaction") {
        return async (callback: (transaction: unknown) => Promise<unknown>) => raw.transaction(async (tx) => callback(wrapDatabase(tx, false)));
      }
      const member = Reflect.get(target, property, receiver) as unknown;
      if (typeof member !== "function") return member;
      return (...args: unknown[]) => {
        const result = Reflect.apply(member, target, args) as unknown;
        return result && typeof result === "object" ? wrapQuery(result) : result;
      };
    },
  });
  return database;
}

export async function checkDatabaseHealth() {
  getDb();
  const startedAt = Date.now();
  await client!.unsafe("select 1 as healthy");
  return { latencyMs: Date.now() - startedAt };
}
